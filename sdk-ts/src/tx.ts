/**
 * Transactions: the TypeScript twin of `btb-chain`'s `tx.rs`, for the kinds a browser app
 * sends itself (transfers and contract calls), including the optional signed `relayer`.
 *
 * Wire form (little-endian): `chain_id:u64 || nonce:u64 || tag:u8 [|| relayer[32]] || fields
 * || public_key[32] || signature[64]`. When a relayer is present the tag byte has its high bit
 * set (`tag | 0x80`) and the 32-byte relayer address follows it; without one the bytes are
 * exactly the original encoding. The signature is Ed25519 over
 * `SHA256("btb.tx.sig.v1" || body)`, so the relayer is covered: nobody who handles the
 * transaction (the relay host, a proposer) can add, drop or change it.
 * `test/fixtures/tx.json` is generated by the Rust crate and checked byte for byte.
 */

const SIG_DOMAIN = new TextEncoder().encode("btb.tx.sig.v1");
const ID_DOMAIN = new TextEncoder().encode("btb.tx.id.v1");
const ACCOUNT_DOMAIN = new TextEncoder().encode("btb.account.v1");
const PKCS8_PREFIX = Uint8Array.from([
  0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x04, 0x22, 0x04, 0x20,
]);
const U64_MAX = (1n << 64n) - 1n;
const RELAYER_FLAG = 0x80;

/** A transaction kind: its tag and encoded fields. */
export interface TxKind {
  tag: number;
  fields: Uint8Array;
}

export interface TxBody {
  chainId: bigint;
  nonce: bigint;
  /** 32-byte address of the hosting node that relays the transaction and earns 20% of the fee. */
  relayer?: Uint8Array;
  kind: TxKind;
}

const bufs = (b: Uint8Array): ArrayBuffer =>
  b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer;

function concat(...parts: Uint8Array[]): Uint8Array {
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let o = 0;
  for (const p of parts) {
    out.set(p, o);
    o += p.length;
  }
  return out;
}

function u64le(x: bigint, what: string): Uint8Array {
  if (typeof x !== "bigint" || x < 0n || x > U64_MAX) throw new RangeError(`${what} is not a u64`);
  const b = new Uint8Array(8);
  new DataView(b.buffer).setBigUint64(0, x, true);
  return b;
}

function u32le(x: number): Uint8Array {
  const b = new Uint8Array(4);
  new DataView(b.buffer).setUint32(0, x, true);
  return b;
}

function bytes32(b: Uint8Array, what: string): Uint8Array {
  if (b.length !== 32) throw new RangeError(`${what} must be 32 bytes`);
  return b;
}

async function sha256(...parts: Uint8Array[]): Promise<Uint8Array> {
  return new Uint8Array(await crypto.subtle.digest("SHA-256", bufs(concat(...parts))));
}

/** `Transfer` (tag 2): move `amount` base units to `to`. */
export function transferKind(to: Uint8Array, amount: bigint): TxKind {
  return { tag: 2, fields: concat(bytes32(to, "to"), u64le(amount, "amount")) };
}

/** `Call` (tag 1) of a contract's `mutation` entry point with already-encoded `args`. */
export function callKind(
  contract: Uint8Array,
  fn: string,
  args: Uint8Array,
  gasLimit: bigint,
  maxFee: bigint = U64_MAX,
): TxKind {
  const name = new TextEncoder().encode(fn);
  return {
    tag: 1,
    fields: concat(
      bytes32(contract, "contract"),
      Uint8Array.of(1), // FunctionKind::Mutation
      u32le(name.length),
      name,
      u32le(args.length),
      args,
      u64le(gasLimit, "gasLimit"),
      u64le(maxFee, "maxFee"),
    ),
  };
}

/** The signed part of a transaction. */
export function encodeTxBody(b: TxBody): Uint8Array {
  const head = concat(u64le(b.chainId, "chainId"), u64le(b.nonce, "nonce"));
  if (b.relayer === undefined) return concat(head, Uint8Array.of(b.kind.tag), b.kind.fields);
  return concat(
    head,
    Uint8Array.of(b.kind.tag | RELAYER_FLAG),
    bytes32(b.relayer, "relayer"),
    b.kind.fields,
  );
}

/** The 32-byte account address of an Ed25519 public key. */
export async function accountAddress(publicKey: Uint8Array): Promise<Uint8Array> {
  return sha256(ACCOUNT_DOMAIN, bytes32(publicKey, "public key"));
}

async function importSeed(seed: Uint8Array): Promise<CryptoKey> {
  bytes32(seed, "seed");
  return crypto.subtle.importKey("pkcs8", bufs(concat(PKCS8_PREFIX, seed)), "Ed25519", true, [
    "sign",
  ]);
}

/** The Ed25519 public key of a 32-byte seed. */
export async function publicKeyOf(seed: Uint8Array): Promise<Uint8Array> {
  const jwk = await crypto.subtle.exportKey("jwk", await importSeed(seed));
  const x = jwk.x!.replace(/-/g, "+").replace(/_/g, "/");
  return Uint8Array.from(atob(x.padEnd(Math.ceil(x.length / 4) * 4, "=")), (c) => c.charCodeAt(0));
}

/** Sign `body` with a 32-byte seed; returns the transaction's wire bytes. */
export async function signTransaction(body: TxBody, seed: Uint8Array): Promise<Uint8Array> {
  const enc = encodeTxBody(body);
  const hash = await sha256(SIG_DOMAIN, enc);
  const key = await importSeed(seed);
  const sig = new Uint8Array(await crypto.subtle.sign("Ed25519", key, bufs(hash)));
  return concat(enc, await publicKeyOf(seed), sig);
}

/** Transaction id: `SHA256("btb.tx.id.v1" || wire bytes)`. */
export async function transactionId(wire: Uint8Array): Promise<Uint8Array> {
  return sha256(ID_DOMAIN, wire);
}
