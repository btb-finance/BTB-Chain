import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  VoucherError,
  VoucherLedger,
  VoucherSpender,
  decodeVoucher,
  encodeVoucher,
  fromHex,
  isStrictEd25519,
  signVoucher,
  toHex,
  verifyVoucher,
  voucherDigest,
} from "../src/index.js";

const fx = JSON.parse(
  readFileSync(new URL("./fixtures/voucher.json", import.meta.url), "utf8"),
) as {
  seed: string;
  public_key: string;
  vouchers: {
    name: string;
    chain_id: string;
    channel_id: string;
    amount: string;
    nonce: string;
    digest: string;
    signature: string;
    bytes: string;
  }[];
  rejected: { name: string; public_key: string; bytes: string }[];
};
const seed = fromHex(fx.seed);
const pk = fromHex(fx.public_key);
const chan = new Uint8Array(32).fill(1);

describe("cross-language fixture (generated by btb-voucher)", () => {
  for (const c of fx.vouchers) {
    it(c.name, async () => {
      const v = {
        chainId: BigInt(c.chain_id),
        channelId: fromHex(c.channel_id),
        amount: BigInt(c.amount),
        nonce: BigInt(c.nonce),
      };
      expect(toHex(await voucherDigest(v))).toBe(c.digest);
      const sv = await signVoucher(v, seed);
      expect(toHex(sv.signature)).toBe(c.signature);
      expect(toHex(encodeVoucher(sv))).toBe(c.bytes);
      const back = decodeVoucher(fromHex(c.bytes));
      expect(back).toEqual(sv);
      expect(await verifyVoucher(back, pk)).toBe(true);
    });
  }
});

describe("strict Ed25519 (negative vectors generated by btb-voucher, rejected there too)", () => {
  for (const c of fx.rejected) {
    it(`rejects ${c.name}`, async () => {
      const sv = decodeVoucher(fromHex(c.bytes));
      expect(await verifyVoucher(sv, fromHex(c.public_key))).toBe(false);
      expect(isStrictEd25519(sv.signature, fromHex(c.public_key))).toBe(false);
    });
  }
  it("has the vectors", () => {
    expect(fx.rejected.length).toBeGreaterThanOrEqual(8);
  });
  it("accepts the valid fixture signatures", () => {
    for (const c of fx.vouchers) {
      expect(isStrictEd25519(fromHex(c.signature), pk)).toBe(true);
    }
  });
});

describe("verification", () => {
  it("rejects tampering and other keys", async () => {
    const sv = await signVoucher({ chainId: 7n, channelId: chan, amount: 5n, nonce: 1n }, seed);
    expect(await verifyVoucher(sv, pk)).toBe(true);
    expect(await verifyVoucher({ ...sv, voucher: { ...sv.voucher, amount: 6n } }, pk)).toBe(false);
    expect(await verifyVoucher({ ...sv, voucher: { ...sv.voucher, chainId: 8n } }, pk)).toBe(false);
    const other = new Uint8Array(32).fill(2);
    expect(await verifyVoucher({ ...sv, voucher: { ...sv.voucher, channelId: other } }, pk)).toBe(
      false,
    );
    const bad = sv.signature.slice();
    bad[3] = bad[3]! ^ 1;
    expect(await verifyVoucher({ ...sv, signature: bad }, pk)).toBe(false);
    expect(await verifyVoucher(sv, new Uint8Array(32).fill(9))).toBe(false);
    expect(await verifyVoucher(sv, new Uint8Array(5))).toBe(false);
  });
  it("rejects values that are not u64 and bad lengths", async () => {
    await expect(
      signVoucher({ chainId: 7n, channelId: chan, amount: -1n, nonce: 1n }, seed),
    ).rejects.toThrow(VoucherError);
    await expect(
      signVoucher({ chainId: 7n, channelId: chan, amount: 1n << 64n, nonce: 1n }, seed),
    ).rejects.toThrow(VoucherError);
    await expect(
      signVoucher({ chainId: 7n, channelId: new Uint8Array(3), amount: 1n, nonce: 1n }, seed),
    ).rejects.toThrow(VoucherError);
    expect(() => decodeVoucher(new Uint8Array(119))).toThrow(VoucherError);
  });
});

const code = async (p: Promise<unknown>) => {
  try {
    await p;
  } catch (e) {
    return (e as VoucherError).code;
  }
  return "no error";
};

describe("accounting", () => {
  it("spender and ledger agree and refuse non-monotonic vouchers", async () => {
    const s = new VoucherSpender(7n, chan, 100n, seed);
    const l = new VoucherLedger(7n, chan, pk, 100n);
    const a = await s.pay(30n);
    const b = await s.pay(20n);
    expect(await l.accept(a)).toBe(30n);
    expect(await l.accept(b)).toBe(20n);
    expect(await code(l.accept(a))).toBe("not_increasing");
    expect(await code(l.accept(b))).toBe("not_increasing");
    expect(l.earned).toBe(50n);
    expect(s.spent).toBe(50n);
    expect(await code(s.pay(0n))).toBe("bad_amount");
    expect(await code(s.pay(51n))).toBe("exceeds_deposit");
    expect(s.spent).toBe(50n);
    s.addDeposit(10n);
    expect(s.remaining).toBe(60n);
    expect(l.best?.voucher.amount).toBe(50n);
  });
  it("ledger refuses other chain, channel, signer, stale nonce and overdraft", async () => {
    const l = new VoucherLedger(7n, chan, pk, 100n);
    const mk = (o: object, k = seed) =>
      signVoucher({ chainId: 7n, channelId: chan, amount: 10n, nonce: 5n, ...o }, k);
    expect(await code(l.accept(await mk({ chainId: 8n })))).toBe("wrong_chain");
    expect(await code(l.accept(await mk({ channelId: new Uint8Array(32).fill(2) })))).toBe(
      "wrong_channel",
    );
    expect(await code(l.accept(await mk({}, new Uint8Array(32).fill(3))))).toBe("bad_signature");
    expect(await code(l.accept(await mk({ amount: 101n })))).toBe("exceeds_deposit");
    expect(await l.accept(await mk({}))).toBe(10n);
    expect(await code(l.accept(await mk({ amount: 20n, nonce: 5n })))).toBe("stale_nonce");
    expect(await code(l.accept(await mk({ amount: 20n, nonce: 6n })))).toBe("no error");
    expect(l.earned).toBe(20n);
  });
});
