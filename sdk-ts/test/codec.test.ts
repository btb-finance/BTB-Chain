import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { CodecError, decode, encode, fromHex, t, toHex } from "../src/index.js";
import { cases } from "./cases.js";

const fixture: Record<string, string> = JSON.parse(
  readFileSync(new URL("./fixtures/codec.json", import.meta.url), "utf8"),
);

describe("cross-language fixture (generated by btb-codec)", () => {
  it("covers exactly the same cases", () => {
    expect(Object.keys(cases).sort()).toEqual(Object.keys(fixture).sort());
  });
  for (const [name, c] of Object.entries(cases)) {
    it(name, () => {
      expect(toHex(encode(c.codec, c.value))).toBe(fixture[name]);
      expect(decode(c.codec, fromHex(fixture[name]!))).toEqual(c.value);
    });
  }
});

describe("docs/ENCODING.md examples", () => {
  const h = (c: any, v: unknown) => toHex(encode(c, v));
  it("encodes", () => {
    expect(h(t.bool, true)).toBe("01");
    expect(h(t.u16, 0x0102)).toBe("0201");
    expect(h(t.u32, 0x01020304)).toBe("04030201");
    expect(h(t.i8, -2)).toBe("fe");
    expect(h(t.i32, -1)).toBe("ffffffff");
    expect(h(t.u128, 1n)).toBe("01" + "00".repeat(15));
    expect(h(t.string, "hi")).toBe("020000006869");
    expect(h(t.string, "")).toBe("00000000");
    expect(h(t.option(t.u8), 5)).toBe("0105");
    expect(h(t.option(t.u8), null)).toBe("00");
    expect(h(t.vec(t.u16), [1, 2])).toBe("0200000001000200");
    expect(h(t.vec(t.u8), [7, 8])).toBe("020000000708");
    expect(h(t.array(t.u16, 2), [1, 2])).toBe("01000200");
    expect(h(t.tuple(t.u8, t.bool), [1, true])).toBe("0101");
    expect(h(t.address, new Uint8Array(32).fill(0xab))).toBe("ab".repeat(32));
  });
});

describe("rejection rules", () => {
  const bad = (c: any, hex: string, max?: number) =>
    expect(() => decode(c, fromHex(hex), max)).toThrow(CodecError);
  it("rejects invalid input", () => {
    bad(t.bool, "02");
    bad(t.option(t.u8), "0200");
    bad(t.u8, "0100"); // trailing
    bad(t.string, "01000000ff"); // bad UTF-8
    bad(t.string, "03000000eda080"); // surrogate
    bad(t.string, "02000000c080"); // overlong
    bad(t.vec(t.u8), "ffffffff"); // over max
    bad(t.vec(t.u8), "03000000", 2 ** 24); // truncated
    bad(t.vec(t.u8), "03000000010203", 2); // custom max
    bad(t.u32, "010203"); // truncated
    bad(t.bytes, "0100"); // truncated body
    bad(t.address, "ab");
  });
  it("does not allocate from an unchecked prefix", () => {
    // 16M elements claimed (within the cap) but no data: fails fast on the first element.
    bad(t.vec(t.u64), "00000001");
  });
  it("rejects out-of-range and malformed values on encode", () => {
    expect(() => encode(t.u8, 256)).toThrow(CodecError);
    expect(() => encode(t.u8, -1)).toThrow(CodecError);
    expect(() => encode(t.u8, 1.5)).toThrow(CodecError);
    expect(() => encode(t.i8, 128)).toThrow(CodecError);
    expect(() => encode(t.u64, 2n ** 64n)).toThrow(CodecError);
    expect(() => encode(t.i64, 2n ** 63n)).toThrow(CodecError);
    expect(() => encode(t.u128, -1n)).toThrow(CodecError);
    expect(() => encode(t.array(t.u8, 2), [1])).toThrow(CodecError);
    expect(() => encode(t.address, new Uint8Array(31))).toThrow(CodecError);
    expect(() => encode(t.string, "\ud800")).toThrow(CodecError);
  });
  it("keeps the BOM and handles round trips", () => {
    const s = "﻿abc";
    expect(decode(t.string, encode(t.string, s))).toBe(s);
  });
});
