#!/bin/sh
# Build the Dioxus frontend to WASM and write ../market-data/web/index.html: one self-contained
# page (the wasm-bindgen glue and the WASM, base64, inline), because `btb dev` serves exactly that
# file at `/`, from the same origin as the contract's /query and /mutation endpoints.
# Needs: rustup target add wasm32-unknown-unknown; cargo install wasm-bindgen-cli --version <the
# wasm-bindgen version in Cargo.lock>.
set -eu
cd "$(dirname "$0")"
cargo build --release --target wasm32-unknown-unknown
out=target/bindgen
rm -rf "$out"
wasm-bindgen --target web --no-typescript --out-dir "$out" \
  target/wasm32-unknown-unknown/release/market-data-web.wasm
if command -v wasm-opt >/dev/null; then
  wasm-opt -Oz -o "$out/market-data-web_bg.wasm" "$out/market-data-web_bg.wasm"
fi
page=../market-data/web/index.html
mkdir -p "$(dirname "$page")"
# Inline everything: snippet imports become data: URLs, the WASM is passed as bytes.
python3 - "$out" "$page" <<'PY'
import base64, os, re, sys
out, page = sys.argv[1], sys.argv[2]
def data_url(path):
    src = open(path, "rb").read()
    return "data:text/javascript;base64," + base64.b64encode(src).decode()
js = open(os.path.join(out, "market-data-web.js")).read()
js = re.sub(r"""from ['"](\./snippets/[^'"]+)['"]""",
            lambda m: 'from "%s"' % data_url(os.path.join(out, m.group(1))), js)
js = re.sub(r"""import\(['"](\./snippets/[^'"]+)['"]\)""",
            lambda m: 'import("%s")' % data_url(os.path.join(out, m.group(1))), js)
wasm = base64.b64encode(open(os.path.join(out, "market-data-web_bg.wasm"), "rb").read()).decode()
html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>BTB Market Data</title>
<style>body{{margin:0;background:#f7f7f5}}@media (prefers-color-scheme: dark){{body{{background:#151514}}}}</style>
</head><body><div id="main"></div>
<!-- Generated by examples/market-data-web/build.sh from Rust (Dioxus). Do not edit. -->
<script type="module">
{js}
const bytes = Uint8Array.from(atob("{wasm}"), c => c.charCodeAt(0));
await __wbg_init({{ module_or_path: bytes }});
</script></body></html>
"""
open(page, "w").write(html)
print(f"wrote {page} ({len(html)} bytes)")
PY
