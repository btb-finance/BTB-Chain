pub const KEY_CONFIG: u8 = 0x01;
pub const KEY_BEACON: u8 = 0x03;
/// DKG window used by the testnet tools: 30 blocks, 15 of them to deal.
pub const DEFAULT_DKG_WINDOW: u64 = 30;
const TAG_OBS: u8 = 0x20;

/// Most feeds a chain can configure.
pub const MAX_PAIRS: usize = 64;
pub const MAX_PAIR_NAME: usize = 32;
/// Most observations a block may carry (extra ones are ignored; `payload_ok` rejects them).
pub const MAX_OBS_PER_BLOCK: usize = 1024;
pub const MAX_AGE_LIMIT: u64 = 100_000;

/// One configured price feed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PairConfig {
    pub id: u32,
    /// For humans and RPC, for example `BTC/USD`.
    pub name: String,
    /// Decimals of the integer price.
    pub decimals: u8,
}

/// Most candidate aggregates the circuit breaker remembers per feed (also the cap of
/// `breaker_window`).
pub const MAX_BREAKER_WINDOW: u64 = 256;
/// Largest `twap_max_window` (matches the VM's `MAX_TWAP_WINDOW`).
pub const MAX_TWAP_WINDOW: u64 = btb_vm::host::abi::MAX_TWAP_WINDOW;
const MAX_BPS: u32 = 1_000_000;

/// When a feed publishes, when it pauses, how far back TWAPs reach (genesis, all feeds).
///
/// The **candidate** is the stake-weighted median of this block (see [`end_block`]). It becomes
/// the published price when it deviates from the published price by more than
/// `update_deviation_bps`, or `heartbeat_blocks` have passed since the last publication.
///
/// The **circuit breaker** (`breaker_bps > 0`) pauses the feed when a candidate lies more than
/// `breaker_bps` away from any candidate of the last `breaker_window` blocks. A paused feed keeps
/// its last price in state, `price` and `price_twap` answer `PRICE_PAUSED`, and nothing is
/// published until `breaker_resume_blocks` consecutive blocks with a candidate each stayed
/// within `breaker_bps` of the previous candidate and of the first candidate of that run. Then
/// the latest candidate is published and the feed is live again. No governance involved.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PriceRules {
    /// Publish when the candidate moves more than this many basis points (0: on any news).
    pub update_deviation_bps: u32,
    /// Publish at least every this many blocks when there is news (at least 1).
    pub heartbeat_blocks: u64,
    /// Breaker threshold in basis points; 0 disables the breaker.
    pub breaker_bps: u32,
    /// Breaker look-back in blocks, `1..=MAX_BREAKER_WINDOW`.
    pub breaker_window: u64,
    /// Consecutive in-band blocks that resume a paused feed (at least 1).
    pub breaker_resume_blocks: u64,
    /// How many blocks back `price_twap` can reach (0: TWAPs off), `<= MAX_TWAP_WINDOW`.
    pub twap_max_window: u64,
}

impl Default for PriceRules {
    /// Publish on every block with news, no breaker, TWAPs up to 1024 blocks.
    fn default() -> Self {
        PriceRules {
            update_deviation_bps: 0,
            heartbeat_blocks: 1,
            breaker_bps: 0,
            breaker_window: 64,
            breaker_resume_blocks: 3,
            twap_max_window: 1024,
        }
    }
}

impl Encode for PriceRules {
    fn encode_to(&self, out: &mut Vec<u8>) {
        self.update_deviation_bps.encode_to(out);
        self.heartbeat_blocks.encode_to(out);
        self.breaker_bps.encode_to(out);
        self.breaker_window.encode_to(out);
        self.breaker_resume_blocks.encode_to(out);
        self.twap_max_window.encode_to(out);
    }
}
impl Decode for PriceRules {
    fn decode_from(r: &mut Reader<'_>) -> Result<Self, DecodeError> {
        Ok(PriceRules {
            update_deviation_bps: u32::decode_from(r)?,
            heartbeat_blocks: u64::decode_from(r)?,
            breaker_bps: u32::decode_from(r)?,
            breaker_window: u64::decode_from(r)?,
            breaker_resume_blocks: u64::decode_from(r)?,
            twap_max_window: u64::decode_from(r)?,
        })
    }
}

impl PriceRules {
    pub fn validate(&self) -> Result<(), String> {
        if self.update_deviation_bps > MAX_BPS || self.breaker_bps > MAX_BPS {
            return Err("basis points above 1,000,000".into());
        }
        if self.heartbeat_blocks == 0 || self.heartbeat_blocks > MAX_AGE_LIMIT {
            return Err(format!("heartbeat_blocks must be 1..={MAX_AGE_LIMIT}"));
        }
        if !(1..=MAX_BREAKER_WINDOW).contains(&self.breaker_window) {
            return Err(format!("breaker_window must be 1..={MAX_BREAKER_WINDOW}"));
        }
        if !(1..=MAX_AGE_LIMIT).contains(&self.breaker_resume_blocks) {
            return Err("breaker_resume_blocks must be at least 1".into());
        }
        if self.twap_max_window > MAX_TWAP_WINDOW {
            return Err(format!("twap_max_window above {MAX_TWAP_WINDOW}"));
        }
        Ok(())
    }
}

/// The oracle section of the genesis: how the beacon key comes about, which feeds exist.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OracleGenesis {
    /// Empty: the validators generate epoch 0's beacon key on chain in the first `dkg_window`
    /// blocks (no trusted party). Otherwise `GroupKey::encode()` of an **interim, trusted-dealer**
    /// key, for testnets only (`--insecure-dealer`); epoch changes then reshare it on chain.
    pub group_key: Vec<u8>,
    /// Consensus key of beacon holder `i` of the interim key (its share's x-coordinate is
    /// `i + 1`); empty when `group_key` is empty.
    pub holders: Vec<[u8; 32]>,
    pub pairs: Vec<PairConfig>,
    /// An observation older than this many blocks is ignored, and so is a price built from
    /// older ones.
    pub max_age_blocks: u64,
    /// Length `W` of the DKG window at the end of every epoch (and at the start of the chain
    /// when `group_key` is empty): `W >= 4` and `2 * W <= epoch_len`.
    pub dkg_window: u64,
    /// Update rule, circuit breaker and TWAP depth of the price feeds.
    pub rules: PriceRules,
}

impl Encode for PairConfig {
    fn encode_to(&self, out: &mut Vec<u8>) {
        self.id.encode_to(out);
        self.name.encode_to(out);
        self.decimals.encode_to(out);
    }
}
impl Decode for PairConfig {
    fn decode_from(r: &mut Reader<'_>) -> Result<Self, DecodeError> {
        Ok(PairConfig {
            id: u32::decode_from(r)?,
            name: String::decode_from(r)?,
            decimals: u8::decode_from(r)?,
        })
    }
}

impl Encode for OracleGenesis {
    fn encode_to(&self, out: &mut Vec<u8>) {
        self.group_key.encode_to(out);
        self.holders.encode_to(out);
        self.pairs.encode_to(out);
        self.max_age_blocks.encode_to(out);
        self.dkg_window.encode_to(out);
        self.rules.encode_to(out);
    }
}
impl Decode for OracleGenesis {
    fn decode_from(r: &mut Reader<'_>) -> Result<Self, DecodeError> {
        Ok(OracleGenesis {
            group_key: Vec::decode_from(r)?,
            holders: Vec::decode_from(r)?,
            pairs: Vec::decode_from(r)?,
            max_age_blocks: u64::decode_from(r)?,
            dkg_window: u64::decode_from(r)?,
            rules: PriceRules::decode_from(r)?,
        })
    }
}

impl OracleGenesis {
    /// Check everything that does not need chain state; returns the parsed interim group key
    /// (`None`: the genesis DKG generates it).
    pub fn validate(&self) -> Result<Option<GroupKey>, String> {
        let group = if self.group_key.is_empty() {
            if !self.holders.is_empty() {
                return Err("beacon holders without a beacon key".into());
            }
            None
        } else {
            let group =
                GroupKey::decode(&self.group_key).map_err(|e| format!("beacon key: {e:?}"))?;
            if self.holders.len() != group.n() {
                return Err("holders and public shares differ in number".into());
            }
            let mut seen = std::collections::BTreeSet::new();
            if !self.holders.iter().all(|h| seen.insert(*h)) {
                return Err("a beacon holder is listed twice".into());
            }
            Some(group)
        };
        if self.dkg_window < dkg::MIN_WINDOW {
            return Err(format!("dkg_window must be at least {}", dkg::MIN_WINDOW));
        }
        if self.pairs.len() > MAX_PAIRS {
            return Err("too many price pairs".into());
        }
        let (mut ids, mut names) = (
            std::collections::BTreeSet::new(),
            std::collections::BTreeSet::new(),
        );
        for p in &self.pairs {
            if p.name.is_empty() || p.name.len() > MAX_PAIR_NAME || p.decimals > 36 {
                return Err(format!("bad price pair {:?}", p.name));
            }
            if !ids.insert(p.id) || !names.insert(p.name.clone()) {
                return Err(format!("price pair {:?} listed twice", p.name));
            }
        }
        if !(1..=MAX_AGE_LIMIT).contains(&self.max_age_blocks) {
            return Err(format!("max_age_blocks must be 1..={MAX_AGE_LIMIT}"));
        }
        self.rules.validate()?;
        Ok(group)
    }

    /// Check against the staking parameters: the genesis window and the tail window of epoch 0
    /// must not overlap.
    pub fn validate_for(&self, epoch_len: u64) -> Result<(), String> {
        if self.dkg_window.saturating_mul(2) > epoch_len {
            return Err(format!(
                "dkg_window {} is more than half the epoch length {epoch_len}",
                self.dkg_window
            ));
        }
        Ok(())
    }
}

pub(crate) fn config_key() -> Vec<u8> {
    vec![TAG_ORACLE, KEY_CONFIG]
}

fn beacon_key() -> Vec<u8> {
    vec![TAG_ORACLE, KEY_BEACON]
}

fn obs_key(pair: u32, key: &[u8; 32]) -> Vec<u8> {
    let mut k = vec![TAG_ORACLE, TAG_OBS];
    k.extend_from_slice(&pair.to_be_bytes());
    k.extend_from_slice(key);
    k
}

fn obs_prefix(pair: u32) -> (Vec<u8>, Vec<u8>) {
    let mut a = vec![TAG_ORACLE, TAG_OBS];
    a.extend_from_slice(&pair.to_be_bytes());
    let mut b = a.clone();
    // the next pair id's prefix is the exclusive end
    let n = pair.checked_add(1);
    match n {
        Some(n) => {
            b.truncate(2);
            b.extend_from_slice(&n.to_be_bytes());
        }
        None => b = vec![TAG_ORACLE, TAG_OBS + 1],
    }
    (a, b)
}

/// What a block brings to the oracles besides its transactions.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct OracleInput {
    /// The beacon signature for this block's height (required when the chain has an oracle
    /// config, forbidden otherwise).
    pub beacon: Option<Beacon>,
    pub observations: Vec<SignedObservation>,
}

impl OracleInput {
    pub fn is_empty(&self) -> bool {
        self.beacon.is_none() && self.observations.is_empty()
    }

    pub fn encode_to(&self, out: &mut Vec<u8>) {
        match &self.beacon {
            Some(b) => {
                1u8.encode_to(out);
                out.extend_from_slice(&b.encode());
            }
            None => 0u8.encode_to(out),
        }
        (self.observations.len() as u32).encode_to(out);
        for o in &self.observations {
            out.extend_from_slice(&o.encode());
        }
    }

    pub fn decode_from(r: &mut Reader<'_>) -> Result<Self, DecodeError> {
        let beacon = match u8::decode_from(r)? {
            0 => None,
            1 => {
                let raw = r.take(16 + 96)?;
                Some(Beacon::decode(raw).ok_or(DecodeError::TrailingBytes)?)
            }
            _ => return Err(DecodeError::TrailingBytes),
        };
        let n = u32::decode_from(r)? as usize;
        if n > MAX_OBS_PER_BLOCK {
            return Err(DecodeError::TrailingBytes);
        }
        let mut observations = Vec::with_capacity(n);
        for _ in 0..n {
            let raw = r.take(btb_oracle::price::OBS_BYTES)?;
            observations.push(SignedObservation::decode(raw).ok_or(DecodeError::TrailingBytes)?);
        }
        Ok(OracleInput {
            beacon,
            observations,
        })
    }
}

/// A price as stored.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PriceEntry {
    pub price: u128,
    pub height: u64,
    pub decimals: u8,
    pub reporters: u32,
}

impl PriceEntry {
    fn encode(&self) -> Vec<u8> {
        let mut o = Vec::with_capacity(29);
        o.extend_from_slice(&self.price.to_le_bytes());
        o.extend_from_slice(&self.height.to_le_bytes());
        o.push(self.decimals);
        o.extend_from_slice(&self.reporters.to_le_bytes());
        o
    }

    fn decode(b: &[u8]) -> Option<PriceEntry> {
        if b.len() != 29 {
            return None;
        }
        Some(PriceEntry {
            price: u128::from_le_bytes(b[..16].try_into().ok()?),
            height: u64::from_le_bytes(b[16..24].try_into().ok()?),
            decimals: b[24],
            reporters: u32::from_le_bytes(b[25..29].try_into().ok()?),
        })
    }
}

/// The oracle config of a chain, if it has one.
pub fn load(kv: &impl KvStore) -> Result<Option<OracleGenesis>, StateError> {
    kv.get(&config_key())?
        .map(|b| OracleGenesis::decode(&b).map_err(StateError::from))
        .transpose()
}

/// The key that signs (and verifies) the beacons of `epoch`; `None` while the chain has none
/// for that epoch (no beacon is required then).
pub fn epoch_key(kv: &impl KvStore, epoch: u64) -> Result<Option<dkg::EpochKey>, StateError> {
    dkg::epoch_key(kv, epoch)
}

/// Does a block of `epoch` need a beacon?
pub fn beacon_required(kv: &impl KvStore, epoch: u64) -> Result<bool, StateError> {
    Ok(load(kv)?.is_some() && dkg::epoch_key(kv, epoch)?.is_some())
}

/// Genesis writes: the config under `50 01`, and the interim key (if any) as epoch 0's.
pub(crate) fn genesis_ops(
    og: &OracleGenesis,
    batch: &mut btb_runtime::WriteBatch,
) -> Result<(), String> {
    if let Some(group) = og.validate()? {
        dkg::genesis_key(&group, &og.holders, batch);
    }
    batch.put(config_key(), og.encode());
    Ok(())
}

/// Start of a block: open a key generation if its window starts here, then verify the beacon
/// against the epoch's key and store its seed.
pub(crate) fn begin_block(
    kv: &mut impl KvStore,
    chain_id: u64,
    cfg: &staking::StakingConfig,
    height: u64,
    input: &OracleInput,
) -> Result<(), String> {
    let loaded = load(&*kv).map_err(|e| e.0)?;
    let Some(og) = loaded else {
        if input.is_empty() {
            return Ok(());
        }
        return Err("block carries oracle input but the chain has no oracle config".into());
    };
    dkg::begin_block(kv, cfg, og.dkg_window, height).map_err(|e| e.0)?;
    crate::cross::begin_block(kv, height).map_err(|e| e.0)?;
    let epoch = cfg.epoch_of_block(height);
    let key = dkg::epoch_key(&*kv, epoch).map_err(|e| e.0)?;
    let Some(key) = key else {
        // The epoch has no key yet (genesis DKG window): no beacon, and no seed that a stale
        // value could be mistaken for.
        if input.beacon.is_some() {
            return Err("block carries a beacon but its epoch has no beacon key".into());
        }
        kv.delete(&oracle_seed_key()).map_err(|e| e.to_string())?;
        return Ok(());
    };
    let Some(beacon) = &input.beacon else {
        return Err("block has no beacon".into());
    };
    if beacon.height != height || beacon.epoch != epoch {
        return Err("beacon is for another height or epoch".into());
    }
    if !beacon.verify(chain_id, &key.group) {
        return Err("beacon signature invalid".into());
    }
    let mut seed_rec = height.to_le_bytes().to_vec();
    seed_rec.extend_from_slice(&beacon.seed());
    kv.put(&oracle_seed_key(), &seed_rec).map_err(|e| e.0)?;
    let mut full = beacon.epoch.to_le_bytes().to_vec();
    full.extend_from_slice(&beacon.height.to_le_bytes());
    full.extend_from_slice(&beacon.signature);
    kv.put(&beacon_key(), &full).map_err(|e| e.0)?;
    Ok(())
}

/// End of a block (after transactions and crons): take in the observations and update prices.
pub(crate) fn end_block(
    kv: &mut impl KvStore,
    chain_id: u64,
    epoch_len: u64,
    height: u64,
    obs: &[SignedObservation],
) -> Result<(), StateError> {
    let Some(og) = load(&*kv)? else {
        return Ok(());
    };
    let og = &og;
    dkg::end_block(kv, epoch_len, height)?;
    crate::cross::end_block(kv, height)?;
    let epoch = height.saturating_sub(1) / epoch_len;
    let Some(rec) = staking::epoch_record(&*kv, epoch)? else {
        return Ok(());
    };
    let stakes: BTreeMap<[u8; 32], u64> = rec
        .validators
        .iter()
        .map(|v| (v.consensus_key, v.stake))
        .collect();
    let total: u128 = stakes.values().map(|s| u128::from(*s)).sum();
    let mut dirty = std::collections::BTreeSet::new();
    for o in obs.iter().take(MAX_OBS_PER_BLOCK) {
        let ob = &o.obs;
        let Some(pair) = og.pairs.iter().find(|p| p.id == ob.pair) else {
            continue;
        };
        if !stakes.contains_key(&o.key)
            || ob.height > height
            || height - ob.height > og.max_age_blocks
            || !o.verify(chain_id)
        {
            continue;
        }
        let k = obs_key(pair.id, &o.key);
        if let Some(prev) = kv.get(&k)? {
            let prev_h = prev
                .get(16..24)
                .and_then(|b| <[u8; 8]>::try_from(b).ok())
                .map_or(0, u64::from_le_bytes);
            if ob.height <= prev_h {
                continue; // a replay or an older statement
            }
        }
        let mut v = ob.price.to_le_bytes().to_vec();
        v.extend_from_slice(&ob.height.to_le_bytes());
        kv.put(&k, &v)?;
        dirty.insert(pair.id);
    }
    for id in dirty {
        let Some(pair) = og.pairs.iter().find(|p| p.id == id) else {
            continue;
        };
        let (start, end) = obs_prefix(id);
        let mut items: Vec<(u128, u64)> = Vec::new();
        let mut reporting: u128 = 0;
        for (k, v) in kv.scan(&start, Some(&end), false, 4096)? {
            let key: Option<[u8; 32]> = k.get(6..38).and_then(|b| b.try_into().ok());
            let (Some(key), true) = (key, v.len() == 24) else {
                continue;
            };
            let h = u64::from_le_bytes(v[16..24].try_into().expect("8 bytes"));
            match stakes.get(&key) {
                Some(stake) if height.saturating_sub(h) <= og.max_age_blocks => {
                    items.push((
                        u128::from_le_bytes(v[..16].try_into().expect("16 bytes")),
                        *stake,
                    ));
                    reporting += u128::from(*stake);
                }
                // stale or no longer a validator: it can never count again
                _ => kv.delete(&k)?,
            }
        }
        // At least two thirds of the stake must have reported fresh observations. Then the
        // honest reporters hold more than half of the reporting weight whenever less than a
        // third of the stake is faulty, so the median is an honest value or between two.
        if total == 0 || reporting * 3 < total * 2 {
            continue;
        }
        if let Some(candidate) = weighted_median(&items) {
            apply_candidate(kv, &og.rules, pair, height, candidate, items.len() as u32)?;
        }
    }
    Ok(())
}

/// `|a - b| > bps / 10000 * b`, saturating (prices above 2^113 compare approximately).
fn moved_more_than(a: u128, reference: u128, bps: u32) -> bool {
    a.abs_diff(reference).saturating_mul(10_000) > reference.saturating_mul(u128::from(bps))
}

/// The circuit-breaker record of a feed (`50 11 pair`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Breaker {
    pub paused: bool,
    /// Consecutive in-band blocks while paused.
    pub in_band: u64,
    /// First candidate of the current in-band run (paused only).
    pub anchor: u128,
    /// The previous candidate.
    pub prev: u128,
    /// `(height, candidate)` of the last `breaker_window` blocks with news, oldest first.
    pub history: Vec<(u64, u128)>,
}

impl Breaker {
    fn encode(&self) -> Vec<u8> {
        let mut o = vec![u8::from(self.paused)];
        o.extend_from_slice(&self.in_band.to_le_bytes());
        o.extend_from_slice(&self.anchor.to_le_bytes());
        o.extend_from_slice(&self.prev.to_le_bytes());
        o.extend_from_slice(&(self.history.len() as u32).to_le_bytes());
        for (h, p) in &self.history {
            o.extend_from_slice(&h.to_le_bytes());
            o.extend_from_slice(&p.to_le_bytes());
        }
        o
    }

    fn decode(b: &[u8]) -> Option<Breaker> {
        let n = u32::from_le_bytes(b.get(41..45)?.try_into().ok()?) as usize;
        if b.len() != 45 + n * 24 || n > MAX_BREAKER_WINDOW as usize {
            return None;
        }
        let history = (0..n)
            .map(|i| {
                let c = &b[45 + i * 24..45 + (i + 1) * 24];
                (
                    u64::from_le_bytes(c[..8].try_into().expect("8")),
                    u128::from_le_bytes(c[8..].try_into().expect("16")),
                )
            })
            .collect();
        Some(Breaker {
            paused: b[0] == 1,
            in_band: u64::from_le_bytes(b[1..9].try_into().ok()?),
            anchor: u128::from_le_bytes(b[9..25].try_into().ok()?),
            prev: u128::from_le_bytes(b[25..41].try_into().ok()?),
            history,
        })
    }
}

/// The breaker record of `pair` (default: live, no history).
pub fn breaker(kv: &impl KvStore, pair: u32) -> Result<Breaker, StateError> {
    Ok(kv
        .get(&oracle_breaker_key(pair))?
        .and_then(|b| Breaker::decode(&b))
        .unwrap_or_default())
}

/// Is the feed of `pair` paused by its circuit breaker?
pub fn paused(kv: &impl KvStore, pair: u32) -> Result<bool, StateError> {
    Ok(breaker(kv, pair)?.paused)
}

fn publish(
    kv: &mut impl KvStore,
    rules: &PriceRules,
    pair: &PairConfig,
    height: u64,
    price: u128,
    reporters: u32,
) -> Result<(), StateError> {
    let e = PriceEntry {
        price,
        height,
        decimals: pair.decimals,
        reporters,
    };
    kv.put(&oracle_price_key(pair.id), &e.encode())?;
    if rules.twap_max_window > 0 {
        btb_runtime::twap::record(kv, pair.id, height, price, rules.twap_max_window)?;
    }
    Ok(())
}

/// A new aggregate (`candidate`) exists at `height`: run the breaker, then the update rule.
fn apply_candidate(
    kv: &mut impl KvStore,
    rules: &PriceRules,
    pair: &PairConfig,
    height: u64,
    candidate: u128,
    reporters: u32,
) -> Result<(), StateError> {
    let cur = price(&*kv, pair.id)?;
    let mut publish_now = false;
    if rules.breaker_bps > 0 {
        let mut br = breaker(&*kv, pair.id)?;
        br.history
            .retain(|(h, _)| height - *h < rules.breaker_window);
        if br.paused {
            let in_band = !moved_more_than(candidate, br.prev, rules.breaker_bps)
                && !moved_more_than(candidate, br.anchor, rules.breaker_bps);
            if in_band {
                br.in_band += 1;
            } else {
                br.in_band = 0;
                br.anchor = candidate;
            }
            br.prev = candidate;
            br.history.push((height, candidate));
            if br.in_band >= rules.breaker_resume_blocks {
                br = Breaker {
                    history: vec![(height, candidate)],
                    prev: candidate,
                    ..Breaker::default()
                };
                publish_now = true;
            }
        } else {
            let lo = br.history.iter().map(|(_, p)| *p).min();
            let hi = br.history.iter().map(|(_, p)| *p).max();
            let jump = lo.is_some_and(|lo| {
                candidate > lo && moved_more_than(candidate, lo, rules.breaker_bps)
            }) || hi.is_some_and(|hi| {
                candidate < hi && moved_more_than(candidate, hi, rules.breaker_bps)
            });
            br.history.push((height, candidate));
            br.prev = candidate;
            if jump {
                br.paused = true;
                br.in_band = 0;
                br.anchor = candidate;
            }
        }
        let paused_now = br.paused;
        kv.put(&oracle_breaker_key(pair.id), &br.encode())?;
        if paused_now {
            return Ok(());
        }
    }
    let due = match cur {
        None => true,
        Some(c) => {
            publish_now
                || height.saturating_sub(c.height) >= rules.heartbeat_blocks
                || moved_more_than(candidate, c.price, rules.update_deviation_bps)
        }
    };
    if due {
        publish(kv, rules, pair, height, candidate, reporters)?;
    }
    Ok(())
}

/// The agreed price of `pair`, if any.
pub fn price(kv: &impl KvStore, pair: u32) -> Result<Option<PriceEntry>, StateError> {
    Ok(kv
        .get(&oracle_price_key(pair))?
        .and_then(|b| PriceEntry::decode(&b)))
}

/// The last block's beacon as stored in state.
pub fn last_beacon(kv: &impl KvStore) -> Result<Option<Beacon>, StateError> {
    Ok(kv.get(&beacon_key())?.and_then(|b| Beacon::decode(&b)))
}

/// Cheap checks a replica can run on a block's oracle input before voting: sizes only (the
/// executor verifies signatures when it executes, and skips bad observations).
pub fn input_ok(input: &OracleInput) -> bool {
    input.observations.len() <= MAX_OBS_PER_BLOCK
}

/// Attach `input` to a block.
pub fn with_input(mut b: Block, input: OracleInput) -> Block {
    b.oracle = input;
    b
}
