//! `btb-node run --config node.json` | `btb-node init-testnet --validators N --dir DIR` |
//! `btb-node peer-id --key FILE` | `btb-node operator-key` | `btb-node assemble-genesis` |
//! `btb-node node-config`. See docs/NODE.md and docs/TESTNET.md.
use btb_node::config::{init_testnet_with, load_key, NodeParams, Oracles};
use btb_node::{open_chain, operators, Node};
use std::path::PathBuf;
use std::process::ExitCode;

const USAGE: &str = "usage:\n\
  btb-node run --config node.json [--rpc 127.0.0.1:PORT] [--data DIR]\n\
  btb-node init-testnet --validators N --dir DIR [--chain-id N] [--base-port P] [--rpc-base-port P]\n\
                        [--oracle true]  (beacon key generated by the validators on chain + demo price feeds)\n\
                        [--insecure-dealer true]  (TESTNET ONLY: this tool deals the beacon key; implies --oracle)\n\
  btb-node peer-id --key validator.key\n\
\n\
  multi-operator network (each operator keeps their own key; see docs/TESTNET.md):\n\
  1 operator:     btb-node operator-key --dir DIR --name NAME --ip PUBLIC_IP [--port 9000]\n\
  2 coordinator:  btb-node assemble-genesis --operators a.json,b.json,... --treasury ADDRESS --out DIR\n\
                    [--chain-id N] [--name NAME] [--stake BTB] [--validator-balance BTB] [--epoch-len N]\n\
  3 operator:     btb-node node-config --dir DIR --genesis genesis.json --peers peers.json --genesis-hash HEX\n\
                    [--port 9000] [--rpc-port 8545] [--data-dir true]\n\
\n\
  --data DIR   keep consensus safety state there; chain state in RocksDB when built with\n\
               --features rocksdb (otherwise a data dir is refused: chain state would be lost)";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("btb-node: {e}\n{USAGE}");
            ExitCode::FAILURE
        }
    }
}

fn flags(args: &[String]) -> Result<Vec<(String, String)>, String> {
    let mut out = Vec::new();
    let mut it = args.iter();
    while let Some(a) = it.next() {
        if !a.starts_with("--") {
            return Err(format!("unexpected argument {a}"));
        }
        out.push((
            a.clone(),
            it.next().ok_or(format!("{a} needs a value"))?.clone(),
        ));
    }
    Ok(out)
}

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let Some((cmd, rest)) = args.split_first() else {
        return Err(String::new());
    };
    let fl = flags(rest)?;
    let get = |k: &str| fl.iter().find(|(f, _)| f == k).map(|(_, v)| v.clone());
    let num = |k: &str, d: u64| -> Result<u64, String> {
        get(k).map_or(Ok(d), |v| {
            v.parse().map_err(|_| format!("{k} needs a number"))
        })
    };
    match cmd.as_str() {
        "init-testnet" => {
            let n = num("--validators", 4)? as usize;
            let dir = PathBuf::from(get("--dir").ok_or("--dir is required")?);
            let dirs = init_testnet_with(
                n,
                &dir,
                num("--chain-id", 7)?,
                num("--base-port", 9000)? as u16,
                num("--rpc-base-port", 8545)? as u16,
                {
                    let on = |k: &str| get(k).is_some_and(|v| v != "false" && v != "0");
                    if on("--insecure-dealer") {
                        Oracles::InsecureDealer
                    } else if on("--oracle") {
                        Oracles::Dkg
                    } else {
                        Oracles::Off
                    }
                },
            )?;
            println!(
                "wrote genesis, faucet key and {} node directories under {}",
                dirs.len(),
                dir.display()
            );
            for d in dirs {
                println!("  btb-node run --config {}/node.json", d.display());
            }
            Ok(())
        }
        "peer-id" => {
            let key = load_key(&PathBuf::from(get("--key").ok_or("--key is required")?))?;
            let id = btb_node::net::peer_id_of(&key.verifying_key().to_bytes()).ok_or("bad key")?;
            println!("{id}");
            Ok(())
        }
        "operator-key" => {
            let dir = PathBuf::from(get("--dir").ok_or("--dir is required")?);
            let name = get("--name").ok_or("--name is required")?;
            let ip = get("--ip")
                .ok_or("--ip (this machine's public IP) is required")?
                .parse()
                .map_err(|e| format!("--ip: {e}"))?;
            let op = operators::operator_key(&dir, &name, ip, num("--port", 9000)? as u16)?;
            println!(
                "wrote {0}/validator.key (secret, mode 0600: never share it)",
                dir.display()
            );
            println!(
                "wrote {0}/operator.json  (public: send it to the coordinator)",
                dir.display()
            );
            println!("  account {}", btb_node::hex::encode(&op.account()));
            println!("  peer    {}", op.peer);
            Ok(())
        }
        "assemble-genesis" => {
            let ops = get("--operators")
                .ok_or("--operators is required")?
                .split(',')
                .map(|f| operators::Operator::load(&PathBuf::from(f.trim())))
                .collect::<Result<Vec<_>, _>>()?;
            let treasury = btb_node::hex::decode32(&get("--treasury").ok_or(
                "--treasury (the account that receives the rest of the supply) is required",
            )?)?;
            let out = PathBuf::from(get("--out").ok_or("--out is required")?);
            let plan = operators::GenesisPlan {
                chain_id: num("--chain-id", 77)?,
                name: get("--name").unwrap_or_else(|| "btb-testnet".into()),
                stake_btb: num("--stake", 100_000)?,
                validator_balance_btb: num("--validator-balance", 1_000_000)?,
                treasury,
                epoch_len: num("--epoch-len", 600)?,
            };
            let hash = operators::assemble_genesis(&ops, &plan, &out)?;
            println!(
                "wrote {0}/genesis.json and {0}/peers.json for {1} validators",
                out.display(),
                ops.len()
            );
            println!("genesis hash (publish it with the files): {hash}");
            Ok(())
        }
        "node-config" => {
            let path = operators::node_config(&operators::NodeConfigPlan {
                dir: PathBuf::from(get("--dir").ok_or("--dir is required")?),
                genesis: PathBuf::from(get("--genesis").ok_or("--genesis is required")?),
                peers: PathBuf::from(get("--peers").ok_or("--peers is required")?),
                genesis_hash: get("--genesis-hash").ok_or("--genesis-hash is required")?,
                port: num("--port", 9000)? as u16,
                rpc_port: num("--rpc-port", 8545)? as u16,
                data_dir: get("--data-dir").is_some_and(|v| v != "false" && v != "0"),
            })?;
            println!("genesis hash matches; wrote {}", path.display());
            println!("  start with: btb-node run --config {}", path.display());
            Ok(())
        }
        "run" => {
            let mut p = NodeParams::load(&PathBuf::from(
                get("--config").ok_or("--config is required")?,
            ))?;
            if let Some(r) = get("--rpc") {
                p.rpc = Some(r.parse().map_err(|e| format!("--rpc: {e}"))?);
            }
            if let Some(d) = get("--data") {
                p.data_dir = Some(PathBuf::from(d));
            }
            start(p)
        }
        _ => Err(format!("unknown command {cmd}")),
    }
}

#[cfg(feature = "rocksdb")]
fn start(p: NodeParams) -> Result<(), String> {
    match p.data_dir.clone() {
        Some(d) => {
            std::fs::create_dir_all(&d).map_err(|e| e.to_string())?;
            #[cfg(feature = "redb")]
            if btb_node::blockstore::redb_selected() {
                let kv = btb_runtime::redb_kv::RedbKv::open(d.join("chain.redb"))
                    .map_err(|e| e.to_string())?;
                println!("btb-node: storage engine redb (experimental)");
                let state = open_chain(kv, &p.genesis)?;
                return serve(p, state);
            }
            let kv =
                btb_runtime::rocks::RocksKv::open(d.join("chain")).map_err(|e| e.to_string())?;
            let state = open_chain(kv, &p.genesis)?;
            serve(p, state)
        }
        None => {
            let state = open_chain(btb_runtime::MemKv::new(), &p.genesis)?;
            serve(p, state)
        }
    }
}

#[cfg(not(feature = "rocksdb"))]
fn start(p: NodeParams) -> Result<(), String> {
    if p.data_dir.is_some() {
        return Err("a data directory needs a build with --features rocksdb \
                    (without it chain state would be lost on restart while the safety state \
                    survives); remove data_dir to run in memory"
            .into());
    }
    let state = open_chain(btb_runtime::MemKv::new(), &p.genesis)?;
    serve(p, state)
}

fn serve<S: btb_runtime::KvStore + Send + 'static>(
    p: NodeParams,
    state: btb_chain::ChainState<S>,
) -> Result<(), String> {
    let listen = p.listen.clone();
    let node = Node::start(p, state)?;
    println!(
        "btb-node: validator started, p2p {listen}, rpc {:?}",
        node.rpc_addr()
    );
    node.run_until_stopped();
    println!("btb-node: stopping");
    node.shutdown();
    Ok(())
}
